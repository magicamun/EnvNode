"""Generate the offline selector from an IANA database compiled with zic.

Usage: generate_timezone_options.py ZONEINFO_DIRECTORY IANA_VERSION
See docs/TimezoneConfiguration.md for the reproducible update procedure.
"""
import argparse
import json
from pathlib import Path

# Keep existing installations' stored strings selectable without migration.
COMPATIBILITY_RULES = {
    'Europe/Berlin': 'CET-1CEST,M3.5.0/2,M10.5.0/3',
    'Europe/London': 'GMT0BST,M3.5.0/1,M10.5.0',
    'UTC': 'UTC0',
    'America/New_York': 'EST5EDT,M3.2.0/2,M11.1.0/2',
    'America/Chicago': 'CST6CDT,M3.2.0/2,M11.1.0/2',
    'America/Denver': 'MST7MDT,M3.2.0/2,M11.1.0/2',
    'America/Los_Angeles': 'PST8PDT,M3.2.0/2,M11.1.0/2',
}


def generate(directory, version):
    options = {}
    for path in sorted(directory.rglob('*')):
        if not path.is_file():
            continue
        data = path.read_bytes()
        if not data.startswith(b'TZif'):
            continue
        name = path.relative_to(directory).as_posix()
        if data[4:5] not in (b'2', b'3', b'4'):
            raise ValueError(f'{name}: TZif file has no POSIX footer')
        rule = data.rsplit(b'\n', 2)[-2].decode('ascii')
        if not rule or len(rule) > 128:
            raise ValueError(f'{name}: missing or oversized POSIX rule')
        options[name] = COMPATIBILITY_RULES.get(name, rule)
    if not all(name in options for name in COMPATIBILITY_RULES):
        raise ValueError('Incomplete IANA database: compatibility zones missing')
    lines = [
        '// Generated by scripts/generate_timezone_options.py; do not edit.',
        f'// IANA tzdata {version}; timezone data is public domain.',
        '// Source: https://data.iana.org/time-zones/ ; see docs/TimezoneConfiguration.md.',
        '// Generator is EnvNode-owned; see root LICENSE. Data retains its public-domain status.',
    ]
    for name, rule in sorted(options.items()):
        lines.append(f'    {{{json.dumps(name)}, {json.dumps(rule)}}},')
    destination = Path(__file__).resolve().parents[1] / 'lib/EnvNodeWebAdmin/include/TimezoneOptions.inc'
    destination.write_text('\n'.join(lines) + '\n')
    print(f'{len(options)} zones written to {destination}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    parser.add_argument('version')
    args = parser.parse_args()
    generate(args.directory, args.version)
